// Production monthly & yearly pricing tiers starting from just ₹99/mo
export function decoratePlansWithPricing(basePlans = []) {
  return basePlans.map((p) => {
    const priceINR = p.durationDays >= 90 ? 299 : p.durationDays >= 60 ? 199 : 99;
    const mrpINR = p.durationDays >= 90 ? 1499 : p.durationDays >= 60 ? 999 : 499;
    const yearlyPriceINR = p.durationDays >= 90 ? 1999 : p.durationDays >= 60 ? 1299 : 799;
    const yearlyMrpINR = p.durationDays >= 90 ? 7999 : p.durationDays >= 60 ? 4999 : 2999;
    const tierGranted = p.durationDays >= 90 ? 'Gold Elite Pro' : 'Pro Athlete';
    return {
      ...p,
      priceINR: p.priceINR ?? priceINR,
      mrpINR: p.mrpINR ?? mrpINR,
      yearlyPriceINR: p.yearlyPriceINR ?? yearlyPriceINR,
      yearlyMrpINR: p.yearlyMrpINR ?? yearlyMrpINR,
      tierGranted: p.tierGranted || tierGranted,
      active: p.active !== false,
    };
  });
}

