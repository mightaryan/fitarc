export function getIngredientThumbnail(ingredientName = '') {
  const lower = ingredientName.toLowerCase();
  for (const [key, url] of Object.entries(INGREDIENT_IMAGE_MAP)) {
    if (lower.includes(key)) {
      return url;
    }
  }
  // Default clean organic food thumbnail
  return 'https://images.unsplash.com/photo-1540420773420-3366772f4999?w=200&auto=format&fit=crop&q=80';
}
